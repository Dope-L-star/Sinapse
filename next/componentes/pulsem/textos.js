export const TEXTOS = { es, en };

/* tx(lang) → el diccionario del idioma, con números y fechas en su formato */
export function tx(lang) {
  const L = TEXTOS[lang] || es;
  const nf = new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'es-CO');
  return Object.assign({}, L, {
    lang,
    fmt: (n) => nf.format(Math.round(n || 0)),
    dec: (n, d = 1) => (+n || 0).toFixed(d).replace('.', lang === 'en' ? '.' : ','),
    agoT: (t) => L.ago(Math.max(0, Math.round((Date.now() - t) / 1000))),
    durT: (ms) => L.dur(Math.round(ms / 60000)),
    when: (t) => new Date(t).toLocaleString(lang === 'en' ? 'en-US' : 'es-CO', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }),
  });
}
